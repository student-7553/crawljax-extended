package com.crawljax.interaction;

/**
 * Geometry mirrored from retro-board {@code LayoutShiftRect}.
 */
public class LayoutShiftRect {

    private double x;
    private double y;
    private double width;
    private double height;
    private double top;
    private double right;
    private double bottom;
    private double left;

    public double getX() {
        return x;
    }

    public double getY() {
        return y;
    }

    public double getWidth() {
        return width;
    }

    public double getHeight() {
        return height;
    }

    public double getTop() {
        return top;
    }

    public double getRight() {
        return right;
    }

    public double getBottom() {
        return bottom;
    }

    public double getLeft() {
        return left;
    }
}
